package core

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

const (
	markerAdminImportsStart  = "// [MAKE:CRUD:ADMIN_IMPORTS_START]"
	markerAdminImportsEnd    = "// [MAKE:CRUD:ADMIN_IMPORTS_END]"
	markerClientImportsStart = "// [MAKE:CRUD:CLIENT_IMPORTS_START]"
	markerClientImportsEnd   = "// [MAKE:CRUD:CLIENT_IMPORTS_END]"

	markerAdminRoutesStart  = "// [MAKE:CRUD:ADMIN_ROUTES_START]"
	markerAdminRoutesEnd    = "// [MAKE:CRUD:ADMIN_ROUTES_END]"
	markerClientRoutesStart = "// [MAKE:CRUD:CLIENT_ROUTES_START]"
	markerClientRoutesEnd   = "// [MAKE:CRUD:CLIENT_ROUTES_END]"
)

// RouteInjectionInfo 描述一个 CRUD 业务切片向 bootstrap/routes.go 注入的必要代码元信息。
type RouteInjectionInfo struct {
	Scope           string // "admin" 或 "client"
	PkgAlias        string // 如 adminproduct 或 clientproduct
	ImportPath      string // 如 "bfiber/internal/features/admin/product"
	ImportStatement string // 格式化后的 import 行
	RouteStatement  string // 格式化后的路由注册语句
}

// DeriveRouteInfo 根据生成选项推导路由注入元信息。
func DeriveRouteInfo(opts GeneratorOptions) RouteInjectionInfo {
	raw := strings.TrimSpace(opts.Name)
	singularSnake := Singularize(ToSnakeCase(raw))
	cleanName := strings.ReplaceAll(singularSnake, "_", "")

	if opts.IsAdmin {
		pkgAlias := "admin" + cleanName
		importPath := "bfiber/internal/features/admin/" + singularSnake
		return RouteInjectionInfo{
			Scope:           "admin",
			PkgAlias:        pkgAlias,
			ImportPath:      importPath,
			ImportStatement: fmt.Sprintf("\t%s \"%s\"", pkgAlias, importPath),
			RouteStatement:  fmt.Sprintf("\t%s.RegisterAdminRoutes(v1, %s.NewHandler(%s.NewService(deps.DBConn())), mw)", pkgAlias, pkgAlias, pkgAlias),
		}
	}

	pkgAlias := "client" + cleanName
	importPath := "bfiber/internal/features/client/" + singularSnake
	return RouteInjectionInfo{
		Scope:           "client",
		PkgAlias:        pkgAlias,
		ImportPath:      importPath,
		ImportStatement: fmt.Sprintf("\t%s \"%s\"", pkgAlias, importPath),
		RouteStatement:  fmt.Sprintf("\t%s.RegisterRoutes(v1, %s.NewHandler(%s.NewService(deps.DBConn())), mw)", pkgAlias, pkgAlias, pkgAlias),
	}
}

// ResolveRoutesFilePath 查找 bootstrap/routes_crud.go 的绝对路径。
func ResolveRoutesFilePath(rootDir string) string {
	return filepath.Join(rootDir, "internal", "bootstrap", "routes_crud.go")
}

// InitialRoutesCrudTemplate 提供 routes_crud.go 默认的初始代码骨架。
const InitialRoutesCrudTemplate = `// Code generated by bfiber make:crud. DO NOT EDIT.

package bootstrap

import (
	"github.com/gofiber/fiber/v3"
	// [MAKE:CRUD:ADMIN_IMPORTS_START]
	// [MAKE:CRUD:ADMIN_IMPORTS_END]
	// [MAKE:CRUD:CLIENT_IMPORTS_START]
	// [MAKE:CRUD:CLIENT_IMPORTS_END]
)

// registerCrudRoutes 注册由 make:crud 脚手架自动生成的领域切片路由。
func registerCrudRoutes(v1 fiber.Router, deps *RouteDeps) {
	mw := deps.Middleware
	_ = mw

	// [MAKE:CRUD:ADMIN_ROUTES_START]
	// [MAKE:CRUD:ADMIN_ROUTES_END]

	// [MAKE:CRUD:CLIENT_ROUTES_START]
	// [MAKE:CRUD:CLIENT_ROUTES_END]
}
`

// InjectRoute 向 internal/bootstrap/routes_crud.go 幂等注入对应 CRUD 模块的 import 与路由注册代码。
func InjectRoute(rootDir string, opts GeneratorOptions) (bool, error) {
	return updateRoutesFile(rootDir, opts, func(content string, info RouteInjectionInfo) (string, bool, error) {
		if strings.Contains(content, info.ImportPath) && strings.Contains(content, info.RouteStatement) {
			return content, false, nil // 幂等直接返回无变更
		}

		importStart, importEnd, routeStart, routeEnd := getMarkers(info.Scope)

		newContent, importInjected := insertBetweenMarkers(content, importStart, importEnd, info.ImportStatement, info.ImportPath)
		if !importInjected {
			return content, false, fmt.Errorf("routes_crud.go markers %s / %s not found", importStart, importEnd)
		}

		finalContent, routeInjected := insertBetweenMarkers(newContent, routeStart, routeEnd, info.RouteStatement, info.RouteStatement)
		if !routeInjected {
			return content, false, fmt.Errorf("routes_crud.go markers %s / %s not found", routeStart, routeEnd)
		}

		return finalContent, true, nil
	})
}

// RemoveRoute 从 internal/bootstrap/routes_crud.go 中安全注销并剔除对应 CRUD 模块的代码。
func RemoveRoute(rootDir string, opts GeneratorOptions) (bool, error) {
	return updateRoutesFile(rootDir, opts, func(content string, info RouteInjectionInfo) (string, bool, error) {
		if !strings.Contains(content, info.ImportPath) && !strings.Contains(content, info.PkgAlias+".Register") {
			return content, false, nil // 原本就不存在
		}

		importStart, importEnd, routeStart, routeEnd := getMarkers(info.Scope)
		newContent := removeBetweenMarkers(content, importStart, importEnd, info.ImportPath)
		finalContent := removeBetweenMarkers(newContent, routeStart, routeEnd, info.PkgAlias+".Register")

		return finalContent, true, nil
	})
}

func updateRoutesFile(rootDir string, opts GeneratorOptions, mutate func(string, RouteInjectionInfo) (string, bool, error)) (bool, error) {
	routesPath := ResolveRoutesFilePath(rootDir)
	contentBytes, err := os.ReadFile(routesPath)
	if err != nil {
		if os.IsNotExist(err) {
			contentBytes = []byte(InitialRoutesCrudTemplate)
		} else {
			return false, fmt.Errorf("failed to read routes_crud.go: %w", err)
		}
	}

	info := DeriveRouteInfo(opts)
	newContent, changed, err := mutate(string(contentBytes), info)
	if err != nil || !changed {
		return false, err
	}

	formatted, err := format.Source([]byte(newContent))
	if err != nil {
		return false, fmt.Errorf("failed to format routes_crud.go: %w", err)
	}

	if err := os.MkdirAll(filepath.Dir(routesPath), 0o755); err != nil { //nolint:gosec // 路由配置文件所在目录需具备标准工程读写权限
		return false, fmt.Errorf("failed to create directory for routes_crud.go: %w", err)
	}

	if err := os.WriteFile(routesPath, formatted, 0o600); err != nil {
		return false, fmt.Errorf("failed to write routes_crud.go: %w", err)
	}

	return true, nil
}

func getMarkers(scope string) (importStart, importEnd, routeStart, routeEnd string) {
	if scope == "admin" {
		return markerAdminImportsStart, markerAdminImportsEnd, markerAdminRoutesStart, markerAdminRoutesEnd
	}
	return markerClientImportsStart, markerClientImportsEnd, markerClientRoutesStart, markerClientRoutesEnd
}

func findMarkerBounds(content, startMarker, endMarker string) (startIdx, endIdx int, ok bool) {
	startIdx = strings.Index(content, startMarker)
	if startIdx == -1 {
		return 0, 0, false
	}
	endIdx = strings.Index(content, endMarker)
	if endIdx == -1 || endIdx < startIdx {
		return 0, 0, false
	}
	return startIdx, endIdx, true
}

func insertBetweenMarkers(content, startMarker, endMarker, toInsert, checkExists string) (string, bool) {
	startIdx, endIdx, ok := findMarkerBounds(content, startMarker, endMarker)
	if !ok {
		return content, false
	}

	if strings.Contains(content[startIdx:endIdx], checkExists) {
		return content, true // 已存在无需重复插入
	}

	insertPos := startIdx + len(startMarker)
	return content[:insertPos] + "\n" + toInsert + content[insertPos:], true
}

func removeBetweenMarkers(content, startMarker, endMarker, matchSubstring string) string {
	startIdx, endIdx, ok := findMarkerBounds(content, startMarker, endMarker)
	if !ok {
		return content
	}

	before := content[:startIdx+len(startMarker)]
	inside := content[startIdx+len(startMarker) : endIdx]
	after := content[endIdx:]

	lines := strings.Split(inside, "\n")
	filtered := make([]string, 0, len(lines))
	for _, line := range lines {
		if !strings.Contains(line, matchSubstring) {
			filtered = append(filtered, line)
		}
	}

	return before + strings.Join(filtered, "\n") + after
}
